import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await (await browser.newContext()).newPage();
page.on('console', m => console.log('CONSOLE', m.type(), m.text().slice(0,200)));
page.on('pageerror', e => console.log('PAGEERROR', e.message));
page.on('request', r => { if (r.url().includes('/api/')) console.log('REQ', r.method(), r.url()); });
page.on('response', async r => { if (r.url().includes('/api/')) console.log('RES', r.status(), (await r.text().catch(()=>'')).slice(0,300)); });
await page.goto('http://127.0.0.1:3000/contact', { waitUntil: 'networkidle' });
await page.waitForTimeout(3000);
await page.fill('#fullName', 'Priya Raman');
await page.fill('#email', 'priya@brightleaf.in');
await page.fill('#phone', '+91 98765 43210');
await page.selectOption('#service', 'SHOPIFY_DEVELOPMENT');
await page.fill('#message', 'We sell handmade furniture and our store is slow on mobile. We want a rebuild with better product pages.');
await page.check('#consent');
console.log('VALID?', await page.evaluate(() => document.querySelector('form').checkValidity()));
await page.click('form button[type="submit"]');
await page.waitForTimeout(6000);
console.log('BODY SNIPPET:', (await page.textContent('form')).replace(/\s+/g,' ').slice(0,300));
await page.screenshot({ path: '/tmp/shots/form-debug.png' });
await browser.close();
